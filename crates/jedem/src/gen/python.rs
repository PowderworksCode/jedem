//! The Python backend: a [pyo3](https://pyo3.rs) extension module.
//!
//! What a Python developer would have written by hand. A synchronous Rust
//! function becomes a synchronous Python function, not a coroutine. A `Result`
//! becomes a raised exception, not an error value the caller must remember to
//! inspect. Names stay `snake_case`, because they already are.

use crate::descriptor::{Op, Surface, Type};
use crate::gen::{generated_marker, GeneratedFile};

/// The rest of a pyo3 extension crate: manifest and module shim.
///
/// The `#[pymodule]` function's name must match the built library's name, which
/// is the one thing that cannot be inferred from the surface alone -- so it is
/// taken from the surface's own name, and `[lib] name` is pinned to match.
pub(super) fn scaffold(
    surface: &Surface,
    core_dir: &str,
    package: &str,
    core_package: &str,
) -> Vec<GeneratedFile> {
    let module = surface.name;
    vec![
        GeneratedFile {
            path: "Cargo.toml".into(),
            contents: format!(
                "{marker}\n\
                 [package]\n\
                 name = \"{package}\"\n\
                 description = \"The Python binding for `{core_package}`, generated by jedem.\"\n\
                 version = \"{version}\"\n\
                 edition = \"2021\"\n\
                 publish = false\n\n\
                 [lib]\n\
                 # Must match the `#[pymodule]` function, and the file Python imports.\n\
                 name = \"{module}\"\n\
                 crate-type = [\"cdylib\"]\n\n\
                 [dependencies]\n\
                 {core_package} = {{ path = \"{core_dir}\" }}\n\
                 pyo3 = {{ version = \"0.23\", features = [\"extension-module\"] }}\n",
                marker = generated_marker("#", surface, "python"),
                version = surface.version,
            ),
        },
        GeneratedFile {
            path: "src/lib.rs".into(),
            contents: format!(
                "{}\n\
                 mod generated;\n\n\
                 #[pyo3::pymodule]\n\
                 fn {module}(m: &pyo3::Bound<'_, pyo3::types::PyModule>) -> pyo3::PyResult<()> {{\n\
                 \x20   generated::register(m)\n\
                 }}\n",
                generated_marker("//", surface, "python"),
            ),
        },
    ]
}

pub(super) fn generate(surface: &Surface, core_path: &str) -> String {
    let mut out = String::new();
    out.push_str(&super::banner(surface, "python"));
    out.push_str(
        r#"
#![allow(clippy::all)]
#![allow(unused_imports)]

use pyo3::exceptions::PyValueError;
use pyo3::prelude::*;

/// A core error surfaces as a Python exception carrying its `Display` text --
/// the idiomatic seam, rather than an error value the caller has to remember
/// to inspect.
fn err(e: impl std::fmt::Display) -> PyErr {
    PyValueError::new_err(e.to_string())
}
"#,
    );

    // Declare every enum the surface reaches, once, with conversions to and
    // from the core's own type. Python gets a real class, not a magic string.
    for def in super::enums_in(surface) {
        out.push_str(&enum_decl(def, core_path));
    }

    let mut registrations = Vec::new();
    for iface in surface.interfaces {
        out.push_str(&format!("\n// ---- {} ----\n\n", iface.name));
        for op in iface.ops {
            let exported = op.export_name.unwrap_or(op.name);
            out.push_str(&op_fn(op, exported, core_path));
            out.push('\n');
            registrations.push(exported.to_string());
        }
    }

    // Enum classes have to be added too, or Python sees the functions but not
    // the type their values belong to.
    let classes: String = super::enums_in(surface)
        .iter()
        .map(|d| format!("    m.add_class::<{}>()?;\n", d.name))
        .collect();
    out.push_str(&format!(
        "/// Register everything on the module. Call this from your `#[pymodule]`.\npub fn register(m: &Bound<'_, PyModule>) -> PyResult<()> {{\n{classes}{}    Ok(())\n}}\n",
        registrations
            .iter()
            .map(|n| format!("    m.add_function(wrap_pyfunction!({n}, m)?)?;\n"))
            .collect::<String>()
    ));
    out
}

/// A pyo3 enum, plus `From` both ways so the core's type never leaks.
fn enum_decl(def: &crate::descriptor::EnumDef, core_path: &str) -> String {
    let mut s = String::new();
    if let Some(doc) = def.doc {
        for line in doc.lines() {
            if line.is_empty() {
                s.push_str("///\n");
            } else {
                s.push_str(&format!("/// {line}\n"));
            }
        }
    }
    s.push_str("#[pyclass(eq, eq_int)]\n#[derive(Clone, Copy, PartialEq, Eq)]\n");
    s.push_str(&format!("pub enum {} {{\n", def.name));
    for v in def.variants {
        if v.wire != v.name {
            s.push_str(&format!("    #[pyo3(name = \"{}\")]\n", v.wire));
        }
        s.push_str(&format!("    {},\n", v.name));
    }
    s.push_str("}\n\n");

    s.push_str(&format!(
        "impl From<{core_path}::{n}> for {n} {{\n    fn from(v: {core_path}::{n}) -> Self {{\n        match v {{\n",
        n = def.name
    ));
    for v in def.variants {
        s.push_str(&format!(
            "            {core_path}::{}::{} => Self::{},\n",
            def.name, v.name, v.name
        ));
    }
    s.push_str("        }\n    }\n}\n\n");

    s.push_str(&format!(
        "impl From<{n}> for {core_path}::{n} {{\n    fn from(v: {n}) -> Self {{\n        match v {{\n",
        n = def.name
    ));
    for v in def.variants {
        s.push_str(&format!(
            "            {}::{} => Self::{},\n",
            def.name, v.name, v.name
        ));
    }
    s.push_str("        }\n    }\n}\n\n");
    s
}

fn op_fn(op: &Op, exported: &str, core_path: &str) -> String {
    let mut s = String::new();
    if let Some(doc) = op.doc {
        for line in doc.lines() {
            // An empty doc line is `///`, not `/// ` -- generated output has to
            // be rustfmt-stable, or `cargo fmt` rewrites it and the drift guard
            // fights the formatter forever.
            if line.is_empty() {
                s.push_str("///\n");
            } else {
                s.push_str(&format!("/// {line}\n"));
            }
        }
    }
    let params: Vec<String> = op
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name, param_ty(&p.ty, p.borrowed)))
        .collect();
    let args: Vec<String> = op
        .params
        .iter()
        .map(|p| match super::convert(&p.ty) {
            Some(c) => format!("{}{c}", p.name),
            None => p.name.to_string(),
        })
        .collect();

    s.push_str("#[pyfunction]\n");
    if exported != op.name {
        s.push_str(&format!("#[pyo3(name = \"{exported}\")]\n"));
    }
    s.push_str(&format!(
        "pub fn {}({}) -> {} {{\n",
        exported,
        params.join(", "),
        return_ty(op)
    ));

    let call = format!("{}::{}({})", core_path, op.rust_path, args.join(", "));
    // An enum crosses as the binding-local type; `From` bridges it, mapped
    // through any container.
    let conv = super::convert(&op.returns);
    s.push_str(&match (op.fallible, op.returns, conv) {
        (true, Type::Unit, _) => format!("    {call}.map_err(err)?;\n    Ok(())\n"),
        (true, _, Some(c)) => format!("    {call}.map(|v| v{c}).map_err(err)\n"),
        (true, _, None) => format!("    {call}.map_err(err)\n"),
        (false, Type::Unit, _) => format!("    {call};\n"),
        (false, _, Some(c)) => format!("    {call}{c}\n"),
        (false, _, None) => format!("    {call}\n"),
    });
    s.push_str("}\n");
    s
}

/// A parameter's Rust spelling in the generated signature.
///
/// Bytes are position-aware: a parameter is a borrowed view (`&[u8]`), so
/// Python's `bytes` crosses without a copy on our side, while a *return* is
/// owned.
fn param_ty(t: &Type, borrowed: bool) -> String {
    match (t, borrowed) {
        (Type::Str, true) => "&str".into(),
        (Type::Bytes, true) => "&[u8]".into(),
        (other, _) => owned_ty(other),
    }
}

/// The owned spelling, used for returns and inside containers.
fn owned_ty(t: &Type) -> String {
    match t {
        Type::Unit => "()".into(),
        Type::Bool => "bool".into(),
        Type::I32 => "i32".into(),
        Type::I64 => "i64".into(),
        Type::F64 => "f64".into(),
        Type::Str => "String".into(),
        Type::Bytes => "Vec<u8>".into(),
        Type::Optional(inner) => format!("Option<{}>", owned_ty(inner)),
        Type::List(inner) => format!("Vec<{}>", owned_ty(inner)),
        // The binding-local enum, not the core's -- they are different types
        // and the generated `From` impls bridge them.
        Type::Enum(d) => d.name.to_string(),
    }
}

fn return_ty(op: &Op) -> String {
    let inner = owned_ty(&op.returns);
    if op.fallible {
        format!("PyResult<{inner}>")
    } else {
        inner
    }
}
