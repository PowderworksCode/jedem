//! The TypeScript backend: a [napi-rs](https://napi.rs) native addon.
//!
//! What a JavaScript developer would have written. Three things follow from
//! that, and none of them is cosmetic:
//!
//! **Names are `camelCase`.** `reverse_bytes` is `reverseBytes` in JS, because
//! that is the name a JS caller expects to type. The Rust function keeps its
//! own name; only the exported spelling changes.
//!
//! **A synchronous function stays synchronous.** No `Promise`, no `AsyncTask`.
//! Wrapping every call in a promise because the machinery exists would be an
//! accent, not a translation — the caller writes `greet(name)`, not
//! `await greet(name)`.
//!
//! **Bytes are position-aware.** A `bytes` *parameter* is a `Uint8Array` — a
//! read-only view the caller already holds — while a `bytes` *return* is a
//! `Buffer`, an owned buffer JS can keep. `Buffer extends Uint8Array`, so the
//! distinction costs nothing at runtime, but the printed `.d.ts` differs and
//! the owned/borrowed intent is exactly what a hand-written binding would
//! express.

use crate::descriptor::{Op, Param, Surface, Type};
use crate::gen::{generated_marker, GeneratedFile};

/// The rest of a napi addon crate: manifest, build script and module shim.
///
/// napi registers each `#[napi]` function at module load, so unlike pyo3 there
/// is no module function -- the shim is one line. The build script is required:
/// it tells the linker to leave Node's symbols unresolved, to be supplied by the
/// host process when the addon loads.
pub(super) fn scaffold(
    surface: &Surface,
    core_dir: &str,
    package: &str,
    core_package: &str,
) -> Vec<GeneratedFile> {
    vec![
        GeneratedFile {
            path: "Cargo.toml".into(),
            contents: format!(
                "{marker}\n\
                 [package]\n\
                 name = \"{package}\"\n\
                 description = \"The Node binding for `{core_package}`, generated by jedem.\"\n\
                 version = \"{version}\"\n\
                 edition = \"2021\"\n\
                 publish = false\n\n\
                 [lib]\n\
                 crate-type = [\"cdylib\"]\n\n\
                 [dependencies]\n\
                 {core_package} = {{ path = \"{core_dir}\" }}\n\
                 napi = {{ version = \"3\", default-features = false, features = [\"napi4\"] }}\n\
                 napi-derive = \"3\"\n\n\
                 [build-dependencies]\n\
                 napi-build = \"2\"\n",
                marker = generated_marker("#", surface, "node"),
                version = surface.version,
            ),
        },
        GeneratedFile {
            path: "build.rs".into(),
            contents: format!(
                "{}\n\
                 fn main() {{\n\
                 \x20   // Leave Node's symbols unresolved; the host supplies them at load.\n\
                 \x20   napi_build::setup();\n\
                 }}\n",
                generated_marker("//", surface, "node"),
            ),
        },
        GeneratedFile {
            path: "src/lib.rs".into(),
            contents: format!(
                "{}\n\
                 // napi registers each function at module load, so there is no\n\
                 // module function to write.\n\
mod generated;\n",
                generated_marker("//", surface, "node"),
            ),
        },
    ]
}

pub(super) fn generate(surface: &Surface, core_path: &str) -> String {
    let mut out = String::new();
    out.push_str(&super::banner(surface, "node"));
    out.push_str(
        r#"
#![allow(clippy::all)]
#![allow(unused_imports)]
// napi registers each function at module load, so nothing in this crate
// references them by name and rustc cannot tell they are used.
#![allow(dead_code)]

use napi::bindgen_prelude::This;
use napi_derive::napi;

/// A core error surfaces as a thrown JS `Error` carrying its `Display` text --
/// the idiomatic seam, rather than an error value the caller has to remember
/// to inspect.
fn err(e: impl std::fmt::Display) -> napi::Error {
    napi::Error::from_reason(e.to_string())
}
"#,
    );
    if surface.interfaces.iter().any(|i| i.consuming) {
        out.push_str(
            r#"
/// A handle is empty only between a builder taking its value out and putting
/// it back, so seeing this means that builder panicked. The handle cannot be
/// repaired -- Rust consumed the value -- so every later call says so.
const EMPTIED: &str = "this handle was emptied by a builder that panicked";
"#,
        );
    }

    // napi's `string_enum` gives TypeScript a string-literal union, which is
    // what a TS developer would have written -- not an opaque number.
    for def in super::enums_in(surface) {
        out.push_str(&enum_decl(def, core_path));
    }

    for iface in surface.interfaces {
        out.push_str(&format!("\n// ---- {} ----\n\n", iface.name));
        if iface.handle {
            out.push_str(&handle_class(iface, core_path));
            out.push('\n');
            continue;
        }
        for op in iface.ops {
            out.push_str(&op_fn(op, core_path));
            out.push('\n');
        }
    }
    out
}

/// A handle: a napi class owning the core value.
///
/// napi class instances are thread-confined, so the class can hold the core
/// value directly rather than behind a lock.
fn handle_class(iface: &crate::descriptor::Interface, core_path: &str) -> String {
    use crate::descriptor::OpKind;
    let name = iface.name;
    let mut s = String::new();
    if let Some(doc) = iface.doc {
        for line in doc.lines() {
            if line.is_empty() {
                s.push_str("///\n");
            } else {
                s.push_str(&format!("/// {line}\n"));
            }
        }
    }
    // A builder has to move the core value out to call, so a handle with one
    // keeps it in an `Option`. Every other handle holds it directly and pays
    // nothing -- no accessor, no unwrap -- for a feature it does not use.
    let (field, wrap, get, get_mut) = if iface.consuming {
        (
            format!("Option<{core_path}::{name}>"),
            "Some(inner)".to_string(),
            "self.get()".to_string(),
            "self.get_mut()".to_string(),
        )
    } else {
        (
            format!("{core_path}::{name}"),
            "inner".to_string(),
            "self.inner".to_string(),
            "self.inner".to_string(),
        )
    };

    s.push_str("#[napi]\n");
    s.push_str(&format!(
        "pub struct {name} {{\n    inner: {field},\n}}\n\n\
         impl From<{core_path}::{name}> for {name} {{\n\
         \x20   fn from(inner: {core_path}::{name}) -> Self {{\n\
         \x20       Self {{ inner: {wrap} }}\n\
         \x20   }}\n\
         }}\n\n"
    ));

    s.push_str(&format!("#[napi]\nimpl {name} {{\n"));

    for op in iface.ops {
        if let Some(doc) = op.doc {
            for line in doc.lines() {
                if line.is_empty() {
                    s.push_str("    ///\n");
                } else {
                    s.push_str(&format!("    /// {line}\n"));
                }
            }
        }
        let params: Vec<String> = op
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, param_ty(p)))
            .collect();
        let args: Vec<String> = op.params.iter().map(arg_expr).collect();

        match op.kind {
            OpKind::Ctor => {
                // One `constructor` per class; napi spells alternates as
                // `factory`, which is what an extra `-> Self` op becomes.
                let primary = op.name == "new";
                if primary {
                    s.push_str("    #[napi(constructor)]\n");
                } else {
                    s.push_str(&format!(
                        "    #[napi(factory, js_name = \"{}\")]\n",
                        js_name(op)
                    ));
                }
                let ret = if op.fallible {
                    "napi::Result<Self>"
                } else {
                    "Self"
                };
                s.push_str(&format!(
                    "    pub fn {}({}) -> {ret} {{\n",
                    op.name,
                    params.join(", ")
                ));
                let call = format!("{core_path}::{name}::{}({})", op.name, args.join(", "));
                if op.fallible {
                    s.push_str(&format!("        Ok({call}.map_err(err)?.into())\n"));
                } else {
                    s.push_str(&format!("        {call}.into()\n"));
                }
            }
            OpKind::Method { mutable } => {
                let recv = if mutable { "&mut self" } else { "&self" };
                let all = std::iter::once(recv.to_string())
                    .chain(params.iter().cloned())
                    .collect::<Vec<_>>()
                    .join(", ");
                s.push_str(&format!("    #[napi(js_name = \"{}\")]\n", js_name(op)));
                s.push_str(&format!(
                    "    pub fn {}({all}){} {{\n",
                    op.name,
                    return_clause(op)
                ));
                let recv = if mutable { &get_mut } else { &get };
                let call = format!("{recv}.{}({})", op.name, args.join(", "));
                s.push_str(&body(op, &call, "        "));
            }
            OpKind::Builder => {
                // The Rust builder consumes `self` and returns `Self`, which
                // names the same object -- the caller's old binding is dead, so
                // nothing can tell in-place mutation apart from it. Returning
                // `this` keeps `new Stream().withX(1).withY(2)` reading the way
                // the Rust chain does, and the way JS builders normally do.
                //
                // `This` is written bare on purpose: napi-derive recognises it
                // by name against a fixed list, so a qualified path is taken
                // for an ordinary argument and the class fails to register.
                s.push_str(&format!("    #[napi(js_name = \"{}\")]\n", js_name(op)));
                let all = std::iter::once("&mut self".to_string())
                    .chain(std::iter::once("this: This<'a>".to_string()))
                    .chain(params.iter().cloned())
                    .collect::<Vec<_>>()
                    .join(", ");
                // The lifetime is named rather than elided: with `&mut self`
                // present, `'_` in return position binds to the receiver, not
                // to `this`.
                s.push_str(&format!(
                    "    pub fn {}<'a>({all}) -> This<'a> {{\n",
                    op.name
                ));
                s.push_str(&format!(
                    "        let inner = self.inner.take().expect(EMPTIED);\n\
                     \x20       self.inner = Some(inner.{}({}));\n\
                     \x20       this\n",
                    op.name,
                    args.join(", ")
                ));
            }
            OpKind::Function => {
                s.push_str(&format!(
                    "    #[napi(factory, js_name = \"{}\")]\n",
                    js_name(op)
                ));
                s.push_str(&format!(
                    "    pub fn {}({}) -> {} {{\n",
                    op.name,
                    params.join(", "),
                    return_ty(op)
                ));
                let call = format!("{core_path}::{name}::{}({})", op.name, args.join(", "));
                s.push_str(&body(op, &call, "        "));
            }
        }
        s.push_str("    }\n\n");
    }
    // The loop leaves a blank line after the last method; rustfmt would remove
    // it, so remove it here.
    while s.ends_with("\n\n") {
        s.pop();
    }
    s.push_str("}\n");
    // The accessors go after the exported block: napi-derive needs the
    // `#[napi]` struct and impl to be adjacent, and an unrelated `impl` in
    // between makes it lose the struct.
    if iface.consuming {
        s.push_str(&format!(
            "impl {name} {{\n\
             \x20   fn get(&self) -> &{core_path}::{name} {{\n\
             \x20       self.inner.as_ref().expect(EMPTIED)\n\
             \x20   }}\n\
             \x20   fn get_mut(&mut self) -> &mut {core_path}::{name} {{\n\
             \x20       self.inner.as_mut().expect(EMPTIED)\n\
             \x20   }}\n\
             }}\n\n"
        ));
    }

    s
}

/// The exported JS spelling: a pinned name verbatim, otherwise the Rust name
/// in `camelCase`.
fn js_name(op: &Op) -> String {
    match op.export_name {
        Some(pinned) => pinned.to_string(),
        None => super::lower_camel(op.name),
    }
}

/// A napi string enum, plus `From` both ways so the core's type never leaks.
fn enum_decl(def: &crate::descriptor::EnumDef, core_path: &str) -> String {
    let mut s = String::new();
    if let Some(doc) = def.doc {
        for line in doc.lines() {
            if line.is_empty() {
                s.push_str("///\n");
            } else {
                s.push_str(&format!("/// {line}\n"));
            }
        }
    }
    s.push_str("#[napi(string_enum)]\n");
    s.push_str(&format!("pub enum {} {{\n", def.name));
    for v in def.variants {
        s.push_str(&format!("    {},\n", v.name));
    }
    s.push_str("}\n\n");

    s.push_str(&format!(
        "impl From<{core_path}::{n}> for {n} {{\n    fn from(v: {core_path}::{n}) -> Self {{\n        match v {{\n",
        n = def.name
    ));
    for v in def.variants {
        s.push_str(&format!(
            "            {core_path}::{}::{} => Self::{},\n",
            def.name, v.name, v.name
        ));
    }
    s.push_str("        }\n    }\n}\n\n");

    s.push_str(&format!(
        "impl From<{n}> for {core_path}::{n} {{\n    fn from(v: {n}) -> Self {{\n        match v {{\n",
        n = def.name
    ));
    for v in def.variants {
        s.push_str(&format!(
            "            {}::{} => Self::{},\n",
            def.name, v.name, v.name
        ));
    }
    s.push_str("        }\n    }\n}\n\n");
    s
}

fn op_fn(op: &Op, core_path: &str) -> String {
    let mut s = String::new();
    if let Some(doc) = op.doc {
        for line in doc.lines() {
            if line.is_empty() {
                s.push_str("///\n");
            } else {
                s.push_str(&format!("/// {line}\n"));
            }
        }
    }

    // Always explicit, even when it matches napi's own default casing:
    // generated code should let a reviewer read the JS name without knowing
    // the generator's conventions.
    s.push_str(&format!("#[napi(js_name = \"{}\")]\n", js_name(op)));

    let params: Vec<String> = op
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name, param_ty(p)))
        .collect();

    s.push_str(&format!(
        "pub fn {}({}) -> {} {{\n",
        op.name,
        params.join(", "),
        return_ty(op)
    ));

    let args: Vec<String> = op.params.iter().map(arg_expr).collect();
    let call = format!("{}::{}({})", core_path, op.rust_path, args.join(", "));

    // A `Vec<u8>` from the core becomes an owned `Buffer` on the way out; for
    // a fallible op the conversion applies to the payload, not the `Result`.
    s.push_str(&body(op, &call, "    "));
    s.push_str("}\n");
    s
}

/// The body of a call. Bytes become an owned Buffer; an enum becomes the
/// binding-local type, mapped through any container.
fn body(op: &Op, call: &str, indent: &str) -> String {
    let conv = if op.returns == Type::Bytes {
        Some(".into()".to_string())
    } else {
        super::convert(&op.returns)
    };
    match (op.fallible, op.returns, conv) {
        (true, Type::Unit, _) => format!("{indent}{call}.map_err(err)?;\n{indent}Ok(())\n"),
        (true, _, Some(c)) => format!("{indent}{call}.map(|v| v{c}).map_err(err)\n"),
        (true, _, None) => format!("{indent}{call}.map_err(err)\n"),
        (false, Type::Unit, _) => format!("{indent}{call};\n"),
        (false, _, Some(c)) => format!("{indent}{call}{c}\n"),
        (false, _, None) => format!("{indent}{call}\n"),
    }
}

/// How the parameter is spelled in the generated napi signature.
///
/// napi hands over owned values, so a core that wants `&str` gets a `String`
/// here and is re-borrowed at the call site — see [`arg_expr`].
fn param_ty(p: &Param) -> String {
    match p.ty {
        Type::Bytes => "napi::bindgen_prelude::Uint8Array".into(),
        Type::Str => "String".into(),
        other => owned_ty(&other),
    }
}

/// How the parameter is passed on to the core.
fn arg_expr(p: &Param) -> String {
    if let Some(c) = super::convert(&p.ty) {
        return format!("{}{c}", p.name);
    }
    match (p.ty, p.borrowed) {
        // `Uint8Array` derefs to `[u8]`, so a borrow reaches a `&[u8]` core.
        (Type::Str, true) | (Type::Bytes, true) => format!("&{}", p.name),
        _ => p.name.to_string(),
    }
}

fn owned_ty(t: &Type) -> String {
    match t {
        Type::Unit => "()".into(),
        Type::Bool => "bool".into(),
        Type::I32 => "i32".into(),
        // napi maps `i64` to a JS `number`, which loses precision beyond
        // 2^53. Faithful for the range JS itself can represent.
        Type::I64 => "i64".into(),
        Type::F64 => "f64".into(),
        Type::Str => "String".into(),
        // Owned position: a JS caller receives a Buffer it can hold.
        Type::Bytes => "napi::bindgen_prelude::Buffer".into(),
        Type::Optional(inner) => format!("Option<{}>", owned_ty(inner)),
        Type::List(inner) => format!("Vec<{}>", owned_ty(inner)),
        // The binding-local enum, not the core's -- they are different types
        // and the generated `From` impls bridge them.
        Type::Enum(d) => d.name.to_string(),
    }
}

fn return_ty(op: &Op) -> String {
    let inner = owned_ty(&op.returns);
    if op.fallible {
        format!("napi::Result<{inner}>")
    } else {
        inner
    }
}

/// The ` -> T` clause, or nothing at all for an infallible unit
/// return -- `-> ()` is noise a hand-written binding would not have.
fn return_clause(op: &Op) -> String {
    if !op.fallible && op.returns == Type::Unit {
        String::new()
    } else {
        format!(" -> {}", return_ty(op))
    }
}
